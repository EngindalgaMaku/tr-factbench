"""Compute pre-adjudication human-human agreement for blind annotation files.

Defaults target the 600-example, 150-context train audit sample generated by
``scripts/41_iaa_sampling.py``. The script also works with Dev600 review files.
Confidence intervals are bootstrapped at context-group level so the four claims
sharing one context are resampled together.
"""
from __future__ import annotations

import argparse
import json
import random
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np
from sklearn.metrics import classification_report, cohen_kappa_score, confusion_matrix

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DIR = ROOT / "results/annotation/train_audit_600"
DEFAULT_A1 = DEFAULT_DIR / "train_audit_600_blind_annotator_1.jsonl"
DEFAULT_A2 = DEFAULT_DIR / "train_audit_600_blind_annotator_2.jsonl"
DEFAULT_OUT = DEFAULT_DIR / "train_audit_600_iaa.json"
DEFAULT_DISAGREEMENTS = DEFAULT_DIR / "train_audit_600_disagreements.jsonl"
LABELS = ["supported", "partially_supported", "contradicted", "unverifiable"]


def read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        raise FileNotFoundError(path)
    return [json.loads(line) for line in path.read_text(encoding="utf-8-sig").splitlines() if line.strip()]


def label_from_row(row: dict) -> str:
    for key in ("final_label", "annotator_label", "label", "annotator1_label", "annotator2_label"):
        value = str(row.get(key, "")).strip()
        if value:
            return value
    return ""


def percentile(values: list[float], q: float) -> float | None:
    if not values:
        return None
    return float(np.percentile(np.asarray(values, dtype=float), q))


def bootstrap_context_ci(pairs: list[dict], iterations: int, seed: int) -> dict:
    grouped: dict[str, list[dict]] = defaultdict(list)
    for row in pairs:
        grouped[row["context_id"]].append(row)
    context_ids = sorted(grouped)
    if len(context_ids) < 2:
        return {"iterations": 0, "percent_agreement_95ci": None, "cohen_kappa_95ci": None}
    rng = random.Random(seed)
    agreements: list[float] = []
    kappas: list[float] = []
    for _ in range(iterations):
        sampled = [rng.choice(context_ids) for _ in context_ids]
        replicate = [row for context_id in sampled for row in grouped[context_id]]
        y1 = [row["label_1"] for row in replicate]
        y2 = [row["label_2"] for row in replicate]
        agreements.append(sum(a == b for a, b in zip(y1, y2)) / len(replicate))
        kappa = cohen_kappa_score(y1, y2, labels=LABELS)
        if not np.isnan(kappa):
            kappas.append(float(kappa))
    return {
        "iterations": iterations,
        "resampling_unit": "context_group",
        "percent_agreement_95ci": [percentile(agreements, 2.5), percentile(agreements, 97.5)],
        "cohen_kappa_95ci": [percentile(kappas, 2.5), percentile(kappas, 97.5)],
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--annotator1", type=Path, default=DEFAULT_A1)
    parser.add_argument("--annotator2", type=Path, default=DEFAULT_A2)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--disagreements", type=Path, default=DEFAULT_DISAGREEMENTS)
    parser.add_argument("--bootstrap-iterations", type=int, default=2000)
    parser.add_argument("--bootstrap-seed", type=int, default=42)
    args = parser.parse_args()

    rows1 = {str(row["example_id"]): row for row in read_jsonl(args.annotator1)}
    rows2 = {str(row["example_id"]): row for row in read_jsonl(args.annotator2)}
    common_ids = sorted(set(rows1) & set(rows2))
    missing_ids = sorted(set(rows1) ^ set(rows2))

    pairs: list[dict] = []
    incomplete: list[str] = []
    invalid: list[dict] = []
    for example_id in common_ids:
        row1 = rows1[example_id]
        row2 = rows2[example_id]
        label1 = label_from_row(row1)
        label2 = label_from_row(row2)
        if not label1 or not label2:
            incomplete.append(example_id)
            continue
        if label1 not in LABELS or label2 not in LABELS:
            invalid.append({"example_id": example_id, "label_1": label1, "label_2": label2})
            continue
        context_id = str(row1.get("context_id") or row2.get("context_id") or example_id)
        domain = str(row1.get("domain") or row2.get("domain") or "")
        pairs.append(
            {
                "example_id": example_id,
                "context_id": context_id,
                "domain": domain,
                "label_1": label1,
                "label_2": label2,
                "agree": label1 == label2,
            }
        )

    expected = max(len(rows1), len(rows2))
    complete = len(pairs) == expected and not missing_ids and not invalid and not incomplete
    result: dict = {
        "annotator1_file": args.annotator1.resolve().relative_to(ROOT.resolve()).as_posix(),
        "annotator2_file": args.annotator2.resolve().relative_to(ROOT.resolve()).as_posix(),
        "expected_examples": expected,
        "matched_examples": len(common_ids),
        "completed_pairs": len(pairs),
        "completed_contexts": len({row["context_id"] for row in pairs}),
        "incomplete_count": len(incomplete),
        "missing_id_count": len(missing_ids),
        "invalid_count": len(invalid),
        "status": "complete" if complete else "incomplete",
        "agreement_stage": "pre_adjudication",
        "weighted_kappa_used": False,
    }

    disagreements = [row for row in pairs if not row["agree"]]
    if pairs:
        y1 = [row["label_1"] for row in pairs]
        y2 = [row["label_2"] for row in pairs]
        by_domain: dict[str, dict] = {}
        for domain in sorted({row["domain"] for row in pairs}):
            domain_rows = [row for row in pairs if row["domain"] == domain]
            dy1 = [row["label_1"] for row in domain_rows]
            dy2 = [row["label_2"] for row in domain_rows]
            by_domain[domain] = {
                "n": len(domain_rows),
                "percent_agreement": sum(a == b for a, b in zip(dy1, dy2)) / len(domain_rows),
                "cohen_kappa": float(cohen_kappa_score(dy1, dy2, labels=LABELS)),
            }
        class_agreement = {}
        for label in LABELS:
            relevant = [row for row in pairs if row["label_1"] == label or row["label_2"] == label]
            class_agreement[label] = {
                "relevant_examples": len(relevant),
                "exact_agreement": sum(row["label_1"] == row["label_2"] == label for row in relevant),
                "agreement_rate": (
                    sum(row["label_1"] == row["label_2"] == label for row in relevant) / len(relevant)
                    if relevant else None
                ),
            }
        result.update(
            {
                "percent_agreement": sum(row["agree"] for row in pairs) / len(pairs),
                "cohen_kappa": float(cohen_kappa_score(y1, y2, labels=LABELS)),
                "confusion_matrix_labels": LABELS,
                "confusion_matrix": confusion_matrix(y1, y2, labels=LABELS).tolist(),
                "classification_report_annotator1_as_reference": classification_report(
                    y1, y2, labels=LABELS, output_dict=True, zero_division=0
                ),
                "disagreement_count": len(disagreements),
                "domain_counts": dict(Counter(row["domain"] for row in pairs)),
                "domain_agreement": by_domain,
                "class_agreement": class_agreement,
                "bootstrap": bootstrap_context_ci(
                    pairs, iterations=args.bootstrap_iterations, seed=args.bootstrap_seed
                ),
            }
        )

    result["incomplete_example_ids_preview"] = incomplete[:20]
    result["missing_example_ids_preview"] = missing_ids[:20]
    result["invalid_rows_preview"] = invalid[:20]

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    args.disagreements.write_text(
        "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in disagreements), encoding="utf-8"
    )
    print(json.dumps({key: result[key] for key in ["status", "expected_examples", "completed_pairs", "incomplete_count"]}, ensure_ascii=False, indent=2))
    if not complete:
        raise SystemExit(2)


if __name__ == "__main__":
    main()
